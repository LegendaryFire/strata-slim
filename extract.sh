#!/usr/bin/env bash
# Take one upstream Strata release into vendor/: only the paths in manifest.txt, then patches/*.patch on top.
#
#   ./extract.sh v0.2.10                         # from the cached mirror in .upstream/ (cloned on first use)
#   UPSTREAM_GIT=/srv/llm/strata/repo ./extract.sh v0.2.10    # from a clone you already have (no download)
#
# vendor/ is replaced as a whole, so `git diff vendor/` afterwards shows exactly what upstream changed in the
# parts this image uses. Nothing is built here; run ./check.py next, then docker build.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
cd "$here"

tag=${1:-}
[ -n "$tag" ] || { echo "usage: $0 <upstream tag, e.g. v0.2.10>" >&2; exit 2; }

UPSTREAM_URL=${UPSTREAM_URL:-https://github.com/Niko1221/Strata.git}
if [ -n "${UPSTREAM_GIT:-}" ]; then
  src=$UPSTREAM_GIT
else
  src=$here/.upstream
  if [ ! -d "$src" ]; then
    echo "[extract] cloning $UPSTREAM_URL into .upstream/ (once)"
    git clone --quiet --bare "$UPSTREAM_URL" "$src"
  fi
  echo "[extract] fetching tags from $UPSTREAM_URL"
  git -C "$src" fetch --quiet --tags --force "$UPSTREAM_URL" '+refs/heads/main:refs/heads/main'
fi

commit=$(git -C "$src" rev-parse --verify --quiet "$tag^{commit}") \
  || { echo "[extract] $tag is not a tag or commit in $src" >&2; exit 2; }

# manifest.txt -> pathspecs ("!x" -> ":(exclude)x")
specs=()
while IFS= read -r line || [ -n "$line" ]; do
  line=${line%%#*}; line=$(printf '%s' "$line" | sed 's/[[:space:]]*$//; s/^[[:space:]]*//')
  [ -n "$line" ] || continue
  case "$line" in
    '!'*) specs+=(":(exclude)${line#!}") ;;
    *)    specs+=("$line") ;;
  esac
done < manifest.txt

# every included (non-exclude) entry must exist upstream: a renamed folder should fail here, not in docker build
missing=0
for s in "${specs[@]}"; do
  case "$s" in ':(exclude)'*) continue ;; esac
  if [ -z "$(git -C "$src" ls-tree -r --name-only "$commit" -- "$s" | head -1)" ]; then
    echo "[extract] manifest entry not in $tag: $s" >&2; missing=1
  fi
done
[ "$missing" = 0 ] || { echo "[extract] fix manifest.txt (upstream moved or removed these)" >&2; exit 1; }

new=$here/vendor.new
rm -rf "$new"; mkdir -p "$new"
git -C "$src" archive --format=tar "$commit" -- "${specs[@]}" | tar -x -C "$new"

# patches/*.patch, in name order, made against the upstream tree (git diff / git format-patch -p1)
shopt -s nullglob
for p in patches/*.patch; do
  echo "[extract] applying $p"
  if ! git apply --directory=vendor.new -p1 --whitespace=nowarn "$p"; then
    echo "[extract] $p does not apply to $tag. Port it, or move it out of patches/ to skip it." >&2
    rm -rf "$new"; exit 1
  fi
done
shopt -u nullglob

# runtime pins: the names in runtime-packages.txt, at upstream's versions
python3 -I - "$new/requirements.txt" runtime-packages.txt "$new/requirements.runtime.txt" <<'PY'
import re, sys
req, names, out = sys.argv[1:4]
want = {l.split("#")[0].strip().lower() for l in open(names) if l.split("#")[0].strip()}
keep, found = [], set()
for line in open(req, encoding="utf-8"):
    s = line.split("#")[0].strip()
    m = re.match(r"([A-Za-z0-9_.-]+)", s)
    if m and m.group(1).lower() in want:
        keep.append(s); found.add(m.group(1).lower())
lost = sorted(want - found)
if lost:
    sys.exit(f"[extract] not in upstream requirements.txt: {', '.join(lost)} (remove from runtime-packages.txt or pin it there)")
open(out, "w").write("# generated by extract.sh from upstream requirements.txt + runtime-packages.txt\n" + "\n".join(keep) + "\n")
PY

# every upstream Python file (check.py uses it to tell "upstream code the manifest left out" from a pip package)
git -C "$src" ls-tree -r --name-only "$commit" | grep '\.py$' > "$new/.upstream-files"

engine_ver=$(sed -n 's/^[[:space:]]*project([^)]*VERSION[[:space:]]*\([0-9][0-9.]*\).*/\1/p' "$new/CMakeLists.txt" | head -1)
llama=$(awk 'NR==1{print $1}' "$new/third_party/ggml/VERSION.txt")
cat > "$new/UPSTREAM" <<EOF
tag=$tag
commit=$commit
date=$(git -C "$src" show -s --format=%cI "$commit")
engine_version=$engine_ver
llama_cpp_commit=$llama
EOF

rm -rf vendor
mv "$new" vendor
echo "[extract] vendor/ = $tag ($commit), engine $engine_ver, $(find vendor -type f | wc -l) files, $(du -sh vendor | cut -f1)"
echo "[extract] next: ./check.py, then git diff --stat vendor/ and docker build"
